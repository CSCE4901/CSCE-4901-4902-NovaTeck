const normalize = value => String(value ?? "").trim().toLowerCase().replace(/\s+/g, " ");
const bySkill = new Map(curatedLearningResources.map(resource => [normalize(resource.skill), resource]));
export function findLearningResource(skill) {
  // An alternative group needs one member; do not confuse SQL with SQL Server.
  return String(skill).split(" / ").map(name => bySkill.get(normalize(name))).find(Boolean) || null;
}
