const filled = value => typeof value === 'string' && value.trim().length > 0;
// Intentionally identical to Dashboard's 10 saved-profile completion checks.
export function profileCompletion(user, details, resume) {
  const checks = [filled(user.name), filled(user.email), filled(details.phone), filled(details.location), filled(details.photo), filled(user.skills), Boolean(resume?.filename), filled(details.college_major), (details.work_types || []).length > 0, filled(details.preferred_location)];
  return Math.round(checks.filter(Boolean).length / checks.length * 100);
}
export const profileSnapshot = (profile, details, skills) => JSON.stringify({ profile, details, skills });
export function profileValidation(profile, details) {
  const errors = {};
  if (!profile.name.trim()) errors.name = 'Enter your full name.';
  if (!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(profile.email)) errors.email = 'Enter a valid email address.';
  if (details.phone && (!/^[+()\d\s.\-xX#eEtT]{7,50}$/.test(details.phone) || details.phone.replace(/\D/g,'').length < 7)) errors.phone = 'Enter a valid phone number, including an area code.';
  (details.experience || []).forEach((entry,index) => {
    if (entry.start && entry.end && entry.end < entry.start) errors[`experience-${index}-end`] = 'End date must be on or after the start date.';
  });
  (details.projects || []).forEach((entry,index) => {
    if (!(entry.title || '').trim()) errors[`project-${index}-title`] = 'Give this project a title.';
    if (entry.url) { try { if (!['http:', 'https:'].includes(new URL(entry.url).protocol)) throw new Error(); } catch { errors[`project-${index}-url`] = 'Enter a complete http:// or https:// link.'; } }
  });
  return errors;
}
